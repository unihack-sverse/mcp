import type { Engine } from '../scan/models.js';

/**
 * A dry-run installation plan for `install_sdk`. The server stores `filesChanged` on the job as
 * metadata only — nothing here writes to disk, deliberately: a bad write into a creator's source
 * tree has no undo in this build, so the diff is produced for review and applied by hand.
 */
export interface SdkPlan {
  sdk: SdkPackage;
  version: string;
  /** Paths `install_sdk` should report as `filesChanged`. */
  filesChanged: string[];
  /** Unified-style diff for every file, ready to copy. */
  diff: string;
  /** Manual steps that are not a file edit (package manager, editor import, config). */
  commands: string[];
  notes: string[];
}

export type SdkPackage = 'sverse-js' | 'sverse-unity' | 'sverse-godot' | 'sverse-payments';

export const SDK_VERSION = '0.1.0';

export const SDK_PACKAGES: SdkPackage[] = ['sverse-js', 'sverse-unity', 'sverse-godot', 'sverse-payments'];

/** Which SDK a detected engine should use. */
export function sdkForEngine(engine: Engine): SdkPackage {
  switch (engine) {
    case 'unity':
      return 'sverse-unity';
    case 'godot':
      return 'sverse-godot';
    default:
      return 'sverse-js';
  }
}

export interface PreviewOptions {
  sdk: SdkPackage;
  version?: string;
  /** Studio handle, used in the generated init call so the snippet is not a placeholder. */
  studioHandle?: string;
  /** Existing frontend files, relative to the project root (used to pick the entry point). */
  existingFiles?: string[];
}

export function buildSdkPlan(options: PreviewOptions): SdkPlan {
  switch (options.sdk) {
    case 'sverse-js':
      return jsPlan(options, false);
    case 'sverse-payments':
      return jsPlan(options, true);
    case 'sverse-unity':
      return unityPlan(options);
    case 'sverse-godot':
      return godotPlan(options);
  }
}

function jsPlan(options: PreviewOptions, paymentsOnly: boolean): SdkPlan {
  const version = options.version ?? SDK_VERSION;
  const handle = options.studioHandle ?? '<studio-handle>';
  const files = options.existingFiles ?? [];
  const entry = pickEntry(files);
  const clientPath = 'src/sverse.ts';
  const storePath = 'src/sverse-store.ts';
  const client = [
    `import { createSverse } from '${options.sdk === 'sverse-payments' ? '@sverse/sverse-payments' : '@sverse/sverse-js'}';`,
    '',
    'export const sverse = createSverse({',
    `  studio: '${handle}',`,
    "  apiUrl: import.meta.env.VITE_SVERSE_API_URL ?? 'http://127.0.0.1:4000',",
    '  onPurchase: (order) => window.dispatchEvent(new CustomEvent(\'sverse:purchase\', { detail: order })),',
    '});',
    '',
  ].join('\n');
  const store = [
    "import { sverse } from './sverse';",
    '',
    '/** Opens the studio store inside the game and resolves when the player confirms. */',
    'export async function openStore() {',
    '  return sverse.store.open();',
    '}',
    '',
  ].join('\n');

  const blocks: string[] = [
    newFileDiff(clientPath, client),
    newFileDiff(storePath, store),
  ];
  if (entry) {
    blocks.push(
      [
        `--- a/${entry}`,
        `+++ b/${entry}`,
        '@@',
        ...(paymentsOnly ? [] : ["+import { sverse } from './sverse';", '+sverse.start();']),
      ].join('\n'),
    );
  }

  const notes = [
    'Nothing was written to disk. Apply the diff manually.',
    'The API key is deliberately absent from client code: the game talks to your backend, not directly to Sverse with a secret key.',
  ];
  if (!entry) notes.push('No entry file was detected, so the import line is not included — add `import { sverse } …` to your game bootstrap yourself.');

  return {
    sdk: options.sdk,
    version,
    filesChanged: [clientPath, storePath, ...(entry ? [entry] : [])],
    diff: blocks.join('\n'),
    commands: options.sdk === 'sverse-payments'
      ? [`npm install @sverse/sverse-payments@${version}`, `echo "VITE_SVERSE_API_URL=http://127.0.0.1:4000" >> .env.local`]
      : [`npm install @sverse/sverse-js@${version}`, `echo "VITE_SVERSE_API_URL=http://127.0.0.1:4000" >> .env.local`],
    notes,
  };
}

function unityPlan(options: PreviewOptions): SdkPlan {
  const version = options.version ?? SDK_VERSION;
  const handle = options.studioHandle ?? '<studio-handle>';
  const path = 'Assets/Sverse/SverseBootstrap.cs';
  const source = [
    'using UnityEngine;',
    '',
    'namespace Sverse {',
    '  /// <summary>Starts the Sverse session. Generated by sverse-mcp; nothing was written to disk.</summary>',
    '  public sealed class SverseBootstrap : MonoBehaviour {',
    `    public string studio = "${handle}";`,
    `    public string sdkVersion = "${version}";`,
    '',
    '    void Awake() {',
    '      DontDestroyOnLoad(gameObject);',
    '      Sverse.Store.Open(studio, sdkVersion);',
    '    }',
    '  }',
    '}',
    '',
  ].join('\n');
  return {
    sdk: 'sverse-unity',
    version,
    filesChanged: [path, 'Assets/Sverse/sverse.config.json'],
    diff: [newFileDiff(path, source), newFileDiff('Assets/Sverse/sverse.config.json', `${JSON.stringify({ studio: handle, sdkVersion: version }, null, 2)}\n`)].join('\n'),
    commands: [
      'Unity Editor: Window > Package Manager > + > Add package from git URL… (ask the studio for the sverse-unity package URL)',
      'Unity Editor: attach SverseBootstrap to a boot scene object',
    ],
    notes: [
      'Nothing was written to disk. Apply the diff manually.',
      'Unity requires an editor import step that a CLI cannot perform; the snippet assumes the Sverse package is installed.',
    ],
  };
}

function godotPlan(options: PreviewOptions): SdkPlan {
  const version = options.version ?? SDK_VERSION;
  const handle = options.studioHandle ?? '<studio-handle>';
  const path = 'addons/sverse/sverse.gd';
  const autoload = 'Sverse=*res://addons/sverse/sverse.gd';
  const source = [
    '# Sverse autoload. Generated by sverse-mcp; nothing was written to disk.',
    'extends Node',
    '',
    `const STUDIO := "${handle}"`,
    `const SDK_VERSION := "${version}"`,
    '',
    'func _ready() -> void:',
    '\tprint("Sverse %s ready for %s" % [SDK_VERSION, STUDIO])',
    '',
    'func open_store() -> void:',
    '\t# Replace with the sverse-godot store call once the addon is installed.',
    '\tpush_warning("Sverse store is not wired yet")',
    '',
  ].join('\n');
  return {
    sdk: 'sverse-godot',
    version,
    filesChanged: [path, 'project.godot'],
    diff: [
      newFileDiff(path, source),
      [
        '--- a/project.godot',
        '+++ b/project.godot',
        '@@ [autoload]',
        `+${autoload}`,
      ].join('\n'),
    ].join('\n'),
    commands: [
      'Project > Project Settings > Autoload, then add res://addons/sverse/sverse.gd as "Sverse" (or apply the diff to project.godot)',
      'Copy the sverse-godot addon into addons/sverse/',
    ],
    notes: ['Nothing was written to disk. Apply the diff manually.', 'Editing project.godot while the editor is open can be overwritten on save — apply it with the editor closed.'],
  };
}

function pickEntry(files: string[]): string | undefined {
  const candidates = ['src/main.ts', 'src/index.ts', 'src/main.js', 'src/index.js', 'src/game.ts', 'src/game.js', 'index.html'];
  const normalized = new Set(files.map((file) => file.replaceAll('\\', '/').toLowerCase()));
  return candidates.find((candidate) => normalized.has(candidate.toLowerCase()));
}

function newFileDiff(path: string, content: string): string {
  const lines = content.split('\n');
  return [`--- /dev/null`, `+++ b/${path}`, `@@ -0,0 +1,${lines.length} @@`, ...lines.map((line) => `+${line}`)].join('\n');
}
